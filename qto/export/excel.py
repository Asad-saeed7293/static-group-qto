def export_changes(pid, path, old=None, new=None):
    """Drawing-revision diff report: what changed between two processing runs - drawings, elements and
    BOQ item quantities - and nothing else. Every row is a stored difference, never an inference, so this
    is safe to hand straight to a client when they reissue drawings."""
    from ..changes import compare_runs
    cmp = compare_runs(pid, old, new)
    p = store.project(pid)
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    if not cmp.get("available"):
        r0 = _title(ws, "Drawing Revision Changes", [f"Project: {p['name']}", cmp.get("reason", "Not available")])
        wb.save(path)
        return path
    sm = cmp["summary"]
    header = [f"Project: {p['name']} - {p.get('location', '')}", f"Comparing run {cmp['old']} (previous) -> {cmp['new']} (current)",
              "Generated by Static Group QTO & BOQ Verification MVP - every row below is a stored difference between the two runs, never an inference."]
    r0 = _title(ws, "Drawing Revision Changes", header)
    _table(ws, r0, ["Metric", "Value"], [
        ["Drawings changed", sm["drawings_changed"]], ["Elements added", sm["elements_added"]],
        ["Elements removed", sm["elements_removed"]], ["Elements modified", sm["elements_modified"]],
        ["BOQ items changed", sm["boq_items_changed"]], ["Concrete volume - previous (m3)", sm["concrete_old_m3"]],
        ["Concrete volume - current (m3)", sm["concrete_new_m3"]],
        ["Concrete volume - change (m3)", round(sm["concrete_new_m3"] - sm["concrete_old_m3"], 3)]],
        [30, 16])

    change_fills = {"added": "C6EFCE", "removed": "FFC7CE", "modified": "FFEB9C"}

    ws2 = wb.create_sheet("Drawings")
