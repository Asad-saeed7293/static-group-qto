def export_changes(pid, path, old=None, new=None):
    """Drawing-revision diff report: what changed between two processing runs - drawings, elements and
    BOQ item quantities - and nothing else. Every row is a stored difference, never an inference, so this
    is safe to hand straight to a client when they reissue drawings."""
    from ..changes import compare_runs
    cmp = compare_runs(pid, old, new)
    p = store.project(pid)
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    if not cmp.get("available"):
        r0 = _title(ws, "Drawing Revision Changes", [f"Project: {p['name']}", cmp.get("reason", "Not available")])
        wb.save(path)
        return path
    sm = cmp["summary"]
    header = [f"Project: {p['name']} - {p.get('location', '')}", f"Comparing run {cmp['old']} (previous) -> {cmp['new']} (current)",
              "Generated by Static Group QTO & BOQ Verification MVP - every row below is a stored difference between the two runs, never an inference."]
    r0 = _title(ws, "Drawing Revision Changes", header)
    _table(ws, r0, ["Metric", "Value"], [
        ["Drawings changed", sm["drawings_changed"]], ["Elements added", sm["elements_added"]],
        ["Elements removed", sm["elements_removed"]], ["Elements modified", sm["elements_modified"]],
        ["BOQ items changed", sm["boq_items_changed"]], ["Concrete volume - previous (m3)", sm["concrete_old_m3"]],
        ["Concrete volume - current (m3)", sm["concrete_new_m3"]],
        ["Concrete volume - change (m3)", round(sm["concrete_new_m3"] - sm["concrete_old_m3"], 3)]],
        [30, 16])

    change_fills = {"added": "C6EFCE", "removed": "FFC7CE", "modified": "FFEB9C"}

    ws2 = wb.create_sheet("Drawings")
    r0 = _title(ws2, "Drawing files changed", header)
    rows = [[d["drawing"], d["change"], "; ".join(d.get("fields", [])), str(d.get("old", "")), str(d.get("new", ""))] for d in cmp["drawings"]]
    _table(ws2, r0, ["Drawing", "Change", "Fields changed", "Previous", "Current"], rows, [55, 12, 24, 30, 30], status_col=2, wrap_cols=(4, 5))
    for i in range(r0 + 1, r0 + 1 + len(rows)):
        s = ws2.cell(row=i, column=2).value
        if s in change_fills:
            ws2.cell(row=i, column=2).fill = PatternFill("solid", fgColor=change_fills[s])

    ws3 = wb.create_sheet("Elements")
    r0 = _title(ws3, "Elements added, removed or modified", header)
    rows = [[e["uid"], e["type"], e["change"], e.get("drawing", ""),
             "; ".join(f"{k}: {a} -> {b}" for k, (a, b) in e.get("dims", {}).items()),
             "; ".join(f"{k}: {a} -> {b}" for k, (a, b) in e.get("quantities", {}).items())] for e in cmp["elements"]]
    _table(ws3, r0, ["Element", "Type", "Change", "Drawing", "Dimension changes", "Quantity changes"], rows,
           [20, 16, 12, 40, 50, 50], status_col=3, wrap_cols=(5, 6))
    for i in range(r0 + 1, r0 + 1 + len(rows)):
        s = ws3.cell(row=i, column=3).value
        if s in change_fills:
            ws3.cell(row=i, column=3).fill = PatternFill("solid", fgColor=change_fills[s])

    ws4 = wb.create_sheet("BOQ Items")
    r0 = _title(ws4, "BOQ item quantities changed", header)
    rows = [[i["item_id"], i["variant"], i["description"], i["unit"], i["old"], i["new"], i["delta"], i["delta_pct"],
             i["old_status"], i["new_status"]] for i in cmp["items"]]
    _table(ws4, r0, ["Item", "Variant", "Description", "Unit", "Previous qty", "Current qty", "Change", "Change %", "Previous status", "Current status"],
           rows, [12, 14, 50, 8, 12, 12, 10, 10, 18, 18], {5: "0.000", 6: "0.000", 7: "0.000", 8: "0.0"}, wrap_cols=(3,))
    wb.save(path)
    return path


