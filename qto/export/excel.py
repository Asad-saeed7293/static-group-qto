NAVY = "1F3A5F"
FILLS = {"Verified": "C6EFCE", "OK": "E2F0D9", "Check": "FFEB9C", "Review Required": "FFC7CE",
         "Missing Data": "D9D9D9", "BOQ not provided": "EDEDED"}
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def _title(ws, title, subtitle_lines):
    ws["A1"] = title
    ws["A1"].font = Font(bold=True, size=14, color=NAVY)
    for i, s in enumerate(subtitle_lines, start=2):
        ws.cell(row=i, column=1, value=s).font = Font(size=9, color="595959", bold=s.startswith("TEST"))
        if s.startswith("TEST"):
            ws.cell(row=i, column=1).font = Font(size=11, color="C00000", bold=True)
    return len(subtitle_lines) + 3


def _table(ws, start_row, headers, rows, widths=None, num_cols=None, status_col=None, wrap_cols=()):
    num_cols = num_cols or {}
    for j, h in enumerate(headers, start=1):
        c = ws.cell(row=start_row, column=j, value=h)
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=NAVY)
        c.alignment = Alignment(vertical="center", wrap_text=True)
        c.border = BORDER
    for i, r in enumerate(rows, start=start_row + 1):
        for j, v in enumerate(r, start=1):
            if isinstance(v, (list, dict)):
                v = "; ".join(map(str, v)) if isinstance(v, list) else str(v)
            c = ws.cell(row=i, column=j, value=v)
            c.border = BORDER
            if j in num_cols and isinstance(v, (int, float)):
                c.number_format = num_cols[j]
            if j in wrap_cols:
                c.alignment = Alignment(wrap_text=True, vertical="top")
            else:
                c.alignment = Alignment(vertical="top")
        if status_col:
            s = r[status_col - 1]
            if s in FILLS:
                ws.cell(row=i, column=status_col).fill = PatternFill("solid", fgColor=FILLS[s])
    for j, w in enumerate(widths or [], start=1):
        ws.column_dimensions[get_column_letter(j)].width = w
    ws.freeze_panes = ws.cell(row=start_row + 1, column=1)
    if rows:
        ws.auto_filter.ref = f"A{start_row}:{get_column_letter(len(headers))}{start_row + len(rows)}"


def _header_lines(pid, data, extra=()):
    p = store.project(pid)
    run = data["run"]
    return [f"Project: {p['name']} - {p.get('location', '')}", f"Processing run: {run['run_id']} ({run['kind']}) finished {run['finished']}",
            f"Source: {p['source_folder']}", "Generated by Static Group QTO & BOQ Verification MVP - quantities derived from DXF geometry; see Calculation Detail for evidence.",
            *extra]


def _fmt_inputs(inputs):
    parts = []
    for k, m in inputs.items():
        v = "n/a" if m["value"] is None else f"{m['value']:.3f}"
        ref = m.get("ref") or {}
        src = f"{m['source']}" + (f" [{ref.get('drawing', '')} {ref.get('layer', '')} #{ref.get('handle', '')}]" if ref else "")
        parts.append(f"{k}={v} {m['unit']} <- {src}: {m['detail']}")
    return "\n".join(parts)


