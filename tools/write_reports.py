def main():
    data = service.results(PID)
    with open(os.path.join(ROOT, "docs", "INSPECTION_REPORT.md"), "w", encoding="utf-8") as fh:
        fh.write(inspection(data))
    with open(os.path.join(ROOT, "docs", "VALIDATION_REPORT.md"), "w", encoding="utf-8") as fh:
        fh.write(validation(data))
    print("reports written")


if __name__ == "__main__":
    main()
