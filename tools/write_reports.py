    cmp = service.comparison(PID)
    queue = service.queue(PID)
    fts = [e for e in els if e["element_type"] in ("footing", "raft")]
    # footing comparison with the Excel prototype
    frows, used = [], set()
    for mark, (l, w, a) in EXCEL_FOOTINGS.items():
        m = [e for e in fts if e["mark"] == mark]
        e = m[0] if m else None
        frows.append([mark, f"{w} × {l}", f"{a}", f"{e['dims']['width']['value']:.3f} × {e['dims']['length']['value']:.3f}" if e else "not found",
                      f3(e["dims"]["plan_area"]["value"]) if e else "", f3(e["dims"]["depth"]["value"]) if e else "",
                      f3(qs[e["uid"]]["value"]) if e else "", "match" if e and abs(e["dims"]["plan_area"]["value"] - a) < 0.02 else "see note"])
    for name, l, w, a in EXCEL_UNVERIFIED:
        e = min(fts, key=lambda x: abs(x["dims"]["plan_area"]["value"] - a))
        frows.append([name, f"{w} × {l}" if w else "irregular", a, e["mark"] or e["uid"], f3(e["dims"]["plan_area"]["value"]),
                      f3(e["dims"]["depth"]["value"]), f3(qs[e["uid"]]["value"]), "now identified" if e["mark"] else "still unidentified"])
    cs = res["design"]["column_schedule"]
    crows = []
