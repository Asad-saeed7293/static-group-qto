"""Generate docs/BOQ_KNOWLEDGE_MODEL.md from config/knowledge/static_boq_model.json (+ benchmarks if present)."""
import os
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from qto import store  # noqa: E402
from qto.knowledge.historical import benchmark_markdown  # noqa: E402
from qto.knowledge.model import load_model  # noqa: E402


def main():
    m = load_model()
    items = m["items"]
    L = ["# Static Group BOQ Knowledge Model", "",
         f"Version {m['version']} · {len(items)} canonical items · source: `config/knowledge/static_boq_model.json` "
         "(generated by `tools/write_knowledge_doc.py` – edit the JSON, not this page).", "",
         "The model generalises Static Group's BOQ lines across projects. Each canonical item records how the line is "
         "worded (match patterns), its unit, the drawings that hold its information, the measurement method and formula, "
         "its dependencies, and how far it can be automated today. One drawing element can feed several items "
         "(e.g. a ground beam → ground-beam concrete, blinding, waterproofing, backfill deduction); the engine keeps the "
         "element→item links for evidence.", "",
         "## Automation status", ""]
    for k, v in Counter(i["automation"] for i in items).most_common():
        L.append(f"* **{k}**: {v}")
    L += ["", "## Items", "",
          "| ID | Category | Description | Unit | Method / formula | Drawing sources | Automation | Engine rule |",
          "|---|---|---|---|---|---|---|---|"]
    for i in items:
        eng = i.get("engine")
        er = "—" if not eng else ("elements: " + "/".join(eng["elements"]) + (f" @ {','.join(eng['floors'])}" if eng.get("floors") else "")
                                 if "elements" in eng else f"= {eng['of']}" if "derived" in eng else "label count" if "text_count" in eng else str(eng))
        meth = (i.get("method", "") + (f" — `{i['formula']}`" if i.get("formula") else "")).replace("|", "/")
        L.append(f"| {i['id']} | {i['category']} | {i['description']} | {i['unit']} | {meth} | {'; '.join(i.get('drawing_sources', []))} | {i['automation']} | {er} |")
    from qto.knowledge.rules_engine import load_rules
    rules = load_rules()
    L += ["", "## Methodology rules", "",
          "Measurement conventions are separate, versioned rules (`config/knowledge/methodology_rules.json`; approvals in "
          "`data/knowledge/rule_state.json`; managed on the **Rule Approval** page). Status: **CONFIRMED** = explicit Static "
          "Group evidence or estimator approval; **INFERRED** = repeated pattern in the historical projects, not confirmed; "
          "**ASSUMED** = temporary development rule; **UNKNOWN** = no option is used – the affected items show a candidate "
          "quantity per option and no value.", "",
          "| Rule | Status | Selected | Options | Items | Evidence |", "|---|---|---|---|---|---|"]
    for r in rules.values():
        opts = "; ".join(f"`{k}`" for k in (r.get("options") or {}))
        L.append(f"| {r['title']} (`{r['rule_id']}`) | {r['status']} | {r.get('selected') or '—'} | {opts} | {', '.join(r.get('items', []))} | {r.get('evidence', '').replace('|', '/')} |")
    L += ["", "## Validation against historical BOQs", "",
          "Classification per measured line: Exact Match (≤0.5 %), Within Tolerance (≤5 %), Difference, Candidates Only (the governing rule is UNKNOWN – candidate quantities are listed, none is chosen), Unable to Calculate. "
          "Differences are reported, not hidden; they are the input for refining the rules.", ""]
    for p in store.projects():
        b = store.read_json(store.pdir(p["id"], "benchmark.json"))
        if b:
            L.append(benchmark_markdown(b, p["name"]))
    with open(os.path.join(ROOT, "docs", "BOQ_KNOWLEDGE_MODEL.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    print("written")


if __name__ == "__main__":
    main()
