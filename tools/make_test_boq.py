"""Create a CLEARLY MARKED synthetic test BOQ to demonstrate the comparison engine.

No real BOQ was supplied for this project. This script takes the generated BOQ
from the latest processing run and applies documented, deterministic changes so
that every comparison outcome can be demonstrated (OK, Check, Review, unit
mismatch, zero quantity, blank quantity, item missing from BOQ, BOQ item not in
drawings, aggregate match across floors). The output is labelled as synthetic on
every sheet and must never be presented as Static Group data.

    python tools/make_test_boq.py  ->  samples/TEST_BOQ_SYNTHETIC_NOT_REAL.xlsx
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from openpyxl import Workbook  # noqa: E402
from openpyxl.styles import Font, PatternFill  # noqa: E402

from qto import service  # noqa: E402

PID = sys.argv[1] if len(sys.argv) > 1 else "ramzi-villa"
FLOOR = {"FDN": "Foundation", "BS": "Basement", "GR": "Ground Floor", "L1": "First Floor", "PH": "Penthouse", "TOR": "Roof"}


def main():
    res = service.results(PID)["results"]
    lines = res["boq"]
    rows, log = [], []
    q_lines = [l for l in lines if l["quantity"] is not None and l["element_id"]]
    omit = {q_lines[i]["item_no"] for i in (4, 21, 40) if i < len(q_lines)}
    special = {}
    if len(q_lines) > 30:
        special[q_lines[10]["item_no"]] = "unit_m2"
        special[q_lines[15]["item_no"]] = "zero"
        special[q_lines[25]["item_no"]] = "blank"
    # columns C5: one BOQ row for all floors (tests aggregate matching)
    c5 = [l for l in lines if l["element_type"] == "column" and l["element_id"] == "C5"]
    skip = {l["item_no"] for l in c5}
    k = 0
    for l in lines:
        if l["item_no"] in omit:
            log.append(f"{l['item_no']} {l['element_id']}: OMITTED from test BOQ (-> 'Drawing item missing from BOQ')")
            continue
        if l["item_no"] in skip:
            continue
        unit, qty = "m3", l["quantity"]
        sp = special.get(l["item_no"])
        if qty is None:
            qty, note = 1.0, "drawing quantity unavailable - arbitrary test value 1.000"
        elif sp == "unit_m2":
            unit, note = "m2", "unit changed to m2 (-> 'Unit mismatch')"
        elif sp == "zero":
            qty, note = 0.0, "quantity set to 0 (-> 'BOQ quantity is zero')"
        elif sp == "blank":
            qty, note = None, "quantity left blank (-> 'BOQ quantity missing')"
        else:
            k += 1
            if k % 7 == 0:
                qty, note = round(qty / 1.035, 3), "drawing is +3.5% vs BOQ (-> Check)"
            elif k % 7 == 3:
                qty, note = round(qty / 0.9176, 3), "drawing is -8.24% vs BOQ (-> Review Required)"
            elif k % 7 == 5:
                qty, note = round(qty / 1.012, 3), "drawing is +1.2% vs BOQ (-> within OK band)"
            else:
                qty, note = round(qty, 3), "same as drawing (-> OK / Verified)"
        rows.append([l["item_no"], l["description"].split(" - ")[0] if l["element_id"] else l["description"],
                     l["element_id"], FLOOR.get(l["floor"], l["floor"]), unit, qty])
        log.append(f"{l['item_no']} {l['element_id'] or l['element_uids'][0]}: {note}")
    if c5:
        tot = round(sum(l["quantity"] or 0 for l in c5), 3)
        rows.append(["07.C5", "Reinforced concrete in column C5 - all floors", "C5", "", "cu.m", tot])
        log.append(f"07.C5 C5: one BOQ row for {len(c5)} drawing lines on different floors, unit written 'cu.m' (-> aggregate match, unit alias)")
    rows.append(["10.01", "Reinforced concrete in lift pit walls", "LPW1", "Basement", "m3", 4.2])
    log.append("10.01 LPW1: item that does not exist in the drawings (-> 'BOQ item not found in drawings')")

    wb = Workbook()
    ws = wb.active
    ws.title = "BOQ"
    ws["A1"] = "TEST BOQ - SYNTHETIC DATA FOR DEMONSTRATION ONLY - NOT STATIC GROUP DATA"
    ws["A1"].font = Font(bold=True, color="C00000", size=13)
    ws["A2"] = "Generated by tools/make_test_boq.py from the drawing-derived quantities with deliberate, documented changes (see sheet 'About this file')."
    hdr = ["Ref", "Item Description", "Element Mark", "Floor", "UoM", "Qty"]
    ws.append([])
    ws.append(hdr)
    for c in ws[4]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="7F7F7F")
    for r in rows:
        ws.append(r)
    for col, w in zip("ABCDEF", (10, 60, 14, 14, 8, 12)):
        ws.column_dimensions[col].width = w
    ab = wb.create_sheet("About this file")
    ab["A1"] = "This is NOT a real Bill of Quantities. It exists only to demonstrate the comparison and review logic."
    ab["A1"].font = Font(bold=True, color="C00000")
    for i, line in enumerate(log, start=3):
        ab.cell(row=i, column=1, value=line)
    ab.column_dimensions["A"].width = 120
    out = os.path.join(ROOT, "samples", "TEST_BOQ_SYNTHETIC_NOT_REAL.xlsx")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    wb.save(out)
    print("wrote", out, len(rows), "rows")


if __name__ == "__main__":
    main()
